import { boolean, index, integer, jsonb, pgTable, real, text, timestamp, uniqueIndex } from "drizzle-orm/pg-core";
import type { AccountRatings, AnalyzedMove, GameSummary, PositionTail } from "@/lib/types";

export const profile = pgTable("profile", {
  id: integer("id").primaryKey(),
  displayName: text("display_name").notNull().default("You"),
  chesscom: text("chesscom").notNull().default(""),
  lichess: text("lichess").notNull().default(""),
  rating: integer("rating").notNull().default(1400),
  depth: integer("depth").notNull().default(12),
  bulkDepth: integer("bulk_depth").notNull().default(10),
  boardTheme: text("board_theme").notNull().default("walnut"),
  pieceSet: text("piece_set").notNull().default("cburnett"),
  coachTone: text("coach_tone").notNull().default("patient"),
  focus: text("focus").notNull().default("all"),
  sound: boolean("sound").notNull().default(true),
  showArrows: boolean("show_arrows").notNull().default(false),
  activeAccountId: text("active_account_id"),
  seeded: boolean("seeded").notNull().default(false),
  updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
});

export const accounts = pgTable("accounts", {
  id: text("id").primaryKey(),
  platform: text("platform").notNull(),
  username: text("username").notNull(),
  displayName: text("display_name").notNull(),
  avatarUrl: text("avatar_url"),
  country: text("country"),
  joinedAt: timestamp("joined_at", { withTimezone: true }),
  ratings: jsonb("ratings").$type<AccountRatings>().notNull().default({}),
  totalGames: integer("total_games").notNull().default(0),
  importedGames: integer("imported_games").notNull().default(0),
  lastSyncedAt: timestamp("last_synced_at", { withTimezone: true }),
  syncStatus: text("sync_status").notNull().default("idle"),
  syncMessage: text("sync_message").notNull().default(""),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
}, (table) => [uniqueIndex("accounts_platform_username_idx").on(table.platform, table.username)]);

export const games = pgTable("games", {
  id: text("id").primaryKey(),
  pgnHash: text("pgn_hash").notNull(),
  source: text("source").notNull(),
  externalUrl: text("external_url"),
  accountId: text("account_id").references(() => accounts.id, { onDelete: "set null" }),
  whiteName: text("white_name").notNull(),
  blackName: text("black_name").notNull(),
  whiteRating: integer("white_rating"),
  blackRating: integer("black_rating"),
  result: text("result").notNull().default("*"),
  youColor: text("you_color"),
  opening: text("opening").notNull().default("Uncharted opening"),
  openingFamily: text("opening_family").notNull().default("Uncharted opening"),
  openingLine: text("opening_line").notNull().default(""),
  eco: text("eco"),
  timeControl: text("time_control"),
  speed: text("speed"),
  rated: boolean("rated").notNull().default(true),
  termination: text("termination"),
  yourResult: text("your_result"),
  oppResult: text("opp_result"),
  endgameType: text("endgame_type"),
  endgameStartPly: integer("endgame_start_ply"),
  endgameDiff: integer("endgame_diff"),
  whiteCastledPly: integer("white_castled_ply"),
  blackCastledPly: integer("black_castled_ply"),
  platformAccuracy: real("platform_accuracy"),
  event: text("event"),
  site: text("site"),
  playedAt: timestamp("played_at", { withTimezone: true }),
  pgn: text("pgn").notNull(),
  initialFen: text("initial_fen").notNull(),
  plyCount: integer("ply_count").notNull().default(0),
  status: text("status").notNull().default("imported"),
  priority: integer("priority").notNull().default(0),
  queuedAt: timestamp("queued_at", { withTimezone: true }),
  analysisError: text("analysis_error"),
  depth: integer("depth"),
  accuracyWhite: real("accuracy_white"),
  accuracyBlack: real("accuracy_black"),
  acplWhite: real("acpl_white"),
  acplBlack: real("acpl_black"),
  estimatedWhite: integer("estimated_white"),
  estimatedBlack: integer("estimated_black"),
  summary: jsonb("summary").$type<GameSummary | null>(),
  moves: jsonb("moves").$type<AnalyzedMove[] | null>(),
  tail: jsonb("tail").$type<PositionTail | null>(),
  notes: text("notes").notNull().default(""),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  analyzedAt: timestamp("analyzed_at", { withTimezone: true }),
}, (table) => [
  uniqueIndex("games_pgn_hash_idx").on(table.pgnHash),
  index("games_account_idx").on(table.accountId),
  index("games_status_idx").on(table.status),
  index("games_external_url_idx").on(table.externalUrl),
  index("games_played_at_idx").on(table.playedAt),
]);

export const drills = pgTable("drills", {
  id: text("id").primaryKey(),
  gameId: text("game_id").notNull().references(() => games.id, { onDelete: "cascade" }),
  accountId: text("account_id"),
  kind: text("kind").notNull().default("improve"),
  found: boolean("found").notNull().default(false),
  ply: integer("ply").notNull(),
  fen: text("fen").notNull(),
  solution: text("solution").notNull(),
  solutionSan: text("solution_san").notNull(),
  playedSan: text("played_san").notNull(),
  prompt: text("prompt").notNull(),
  theme: text("theme").notNull(),
  classification: text("classification").notNull(),
  attempts: integer("attempts").notNull().default(0),
  solved: integer("solved").notNull().default(0),
  lastResult: text("last_result"),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
}, (table) => [index("drills_game_idx").on(table.gameId), index("drills_account_idx").on(table.accountId)]);

export const theoryProgress = pgTable("theory_progress", {
  id: text("id").primaryKey(),
  uid: text("uid").notNull(),
  moduleId: text("module_id").notNull(),
  correct: integer("correct").notNull().default(0),
  attempts: integer("attempts").notNull().default(0),
  bestScore: integer("best_score").notNull().default(0),
  notes: text("notes").notNull().default(""),
  completedAt: timestamp("completed_at", { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
}, (table) => [uniqueIndex("theory_uid_module_idx").on(table.uid, table.moduleId), index("theory_uid_idx").on(table.uid)]);

export const syncCursors = pgTable("sync_cursors", {
  id: text("id").primaryKey(),
  scope: text("scope").notNull(),
  cursor: integer("cursor").notNull().default(0),
  untouched: integer("untouched").notNull().default(0),
  complete: boolean("complete").notNull().default(false),
  updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
});

export const referenceGames = pgTable("reference_games", {
  id: text("id").primaryKey(),
  externalUrl: text("external_url"),
  source: text("source").notNull(),
  whiteName: text("white_name").notNull(),
  blackName: text("black_name").notNull(),
  whiteElo: integer("white_elo"),
  blackElo: integer("black_elo"),
  result: text("result").notNull(),
  opening: text("opening").notNull().default("Uncharted opening"),
  openingFamily: text("opening_family").notNull().default("Uncharted opening"),
  eco: text("eco"),
  event: text("event"),
  speed: text("speed"),
  playedAt: timestamp("played_at", { withTimezone: true }),
  pgn: text("pgn").notNull(),
  initialFen: text("initial_fen").notNull(),
  midgameFen: text("midgame_fen").notNull(),
  midgamePly: integer("midgame_ply").notNull().default(0),
  plyCount: integer("ply_count").notNull().default(0),
  tags: jsonb("tags").$type<string[]>().notNull().default([]),
  era: text("era"),
  tier: text("tier"),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
}, (table) => [uniqueIndex("reference_url_idx").on(table.externalUrl), index("reference_players_idx").on(table.whiteName, table.blackName), index("reference_opening_idx").on(table.openingFamily)]);
